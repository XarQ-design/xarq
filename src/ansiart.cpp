bool decodeTextArt(const QByteArray& data, const QString& ext, TextArt* out){
    const uchar* p = reinterpret_cast<const uchar*>(data.constData());
    qint64 n = data.size();
    // SAUCE: a 128-byte record at the end, maybe after comment lines and the end-of-file mark.
    int sauceWidth = 0, sauceRows = 0; bool ice = false, nine = false; int dataType = -1, fileType = -1;
    if(n >= 128 && !std::memcmp(p + n - 128, "SAUCE00", 7)){
        const uchar* s = p + n - 128;
        auto field = [&](int at, int len){ return QString::fromLatin1(reinterpret_cast<const char*>(s + at), len).trimmed(); };
        out->title = field(7, 35); out->author = field(42, 20); out->group = field(62, 20);
        dataType = s[94]; fileType = s[95];
        sauceWidth = s[96] | s[97] << 8; sauceRows = s[98] | s[99] << 8;
        const int comments = s[104], flags = s[105];
        ice = flags & 1; nine = ((flags >> 1) & 3) == 2;
        n -= 128;
        if(comments > 0 && n >= 5 + 64 * comments && !std::memcmp(p + n - 5 - 64 * comments, "COMNT", 5)) n -= 5 + 64 * comments;
        if(n > 0 && p[n - 1] == 0x1a) --n;
    }
    Grid g; QVector<QRgb> pal(16); for(int i = 0; i < 16; ++i) pal[i] = kAnsi[kIbmToAnsi[i]];
    const uchar* font = kVga; const uchar* highFont = nullptr; int fontH = 16;
    const QString e = ext.toLower();
    if(n >= 11 && !std::memcmp(p, "XBIN\x1a", 5)){                          // XBin
        const int w = p[5] | p[6] << 8, h = p[7] | p[8] << 8, flags = p[10];
        fontH = p[9] ? p[9] : 16;
        if(w < 1 || w > 4096 || fontH > 32 || h > 100000) return false;
        qint64 o = 11;
        if(flags & 1){ if(o + 48 > n) return false; for(int i = 0; i < 16; ++i) pal[i] = sixBit(p + o + i * 3); o += 48; }
        if(flags & 2){ const qint64 fs = qint64(fontH) * 256; if(o + fs > n) return false; font = p + o; o += fs;
                       if(flags & 0x10){ if(o + fs > n) return false; highFont = p + o; o += fs; } }
        else fontH = 16;
        g.columns = w;
        if(flags & 4){                                                       // run-length compressed
            qint64 k = 0; const qint64 total = qint64(w) * h;
            while(o < n && k < total){
                const int type = p[o] & 0xc0, count = (p[o] & 0x3f) + 1; ++o;
                int ch = -1, at = -1;
                for(int r = 0; r < count && k < total; ++r){
                    if(type == 0x00){ if(o + 2 > n) break; ch = p[o]; at = p[o + 1]; o += 2; }
                    else if(type == 0x40){ if(ch < 0){ if(o >= n) break; ch = p[o++]; } if(o >= n) break; at = p[o++]; }
                    else if(type == 0x80){ if(at < 0){ if(o >= n) break; at = p[o++]; } if(o >= n) break; ch = p[o++]; }
                    else { if(ch < 0){ if(o >= n) break; ch = p[o++]; } if(at < 0){ if(o >= n) break; at = p[o++]; } }
                    Cell c; c.ch = uchar(ch); c.fg = pal[at & 15]; c.bg = pal[(at >> 4) & 15]; c.high = highFont && (at & 8);
                    g.put(int(k / w), int(k % w), c); ++k;
                }
            }
        } else pairs(p + o, n - o, w, true, pal.constData(), g);
    } else if(n >= 9 && p[0] == 24 && !std::memcmp(p + 1, "TUNDRA24", 8)){   // TundraDraw
        g.columns = sauceWidth > 0 ? sauceWidth : 80;
        QRgb fg = kAnsi[7], bg = kAnsi[0]; int row = 0, col = 0;
        for(qint64 o = 9; o < n; ++o){
            if(col >= g.columns){ col = 0; ++row; }
            int ch = p[o];
            if(ch == 1){ if(o + 8 >= n) break; row = int(quint32(p[o+1]) << 24 | p[o+2] << 16 | p[o+3] << 8 | p[o+4]); col = int(quint32(p[o+5]) << 24 | p[o+6] << 16 | p[o+7] << 8 | p[o+8]); o += 8; continue; }
            if(ch == 2){ if(o + 5 >= n) break; fg = qRgb(p[o+3], p[o+4], p[o+5]); ch = p[o+1]; o += 5; }
            else if(ch == 4){ if(o + 5 >= n) break; bg = qRgb(p[o+3], p[o+4], p[o+5]); ch = p[o+1]; o += 5; }
            else if(ch == 6){ if(o + 9 >= n) break; fg = qRgb(p[o+3], p[o+4], p[o+5]); bg = qRgb(p[o+7], p[o+8], p[o+9]); ch = p[o+1]; o += 9; }
            Cell c; c.ch = uchar(ch); c.fg = fg; c.bg = bg; g.put(row, col, c); ++col;
        }
    } else if(e == QLatin1String("xb") || e == QLatin1String("tnd")){       // named so, but without the header
        return false;
    } else if(e == QLatin1String("adf")){                                     // ArtWorx: palette, font, then pairs
        if(n < 4289) return false;
        static const int idx[16] = {0, 1, 2, 3, 4, 5, 20, 7, 56, 57, 58, 59, 60, 61, 62, 63};
        for(int i = 0; i < 16; ++i) pal[i] = sixBit(p + 1 + idx[i] * 3);
        font = p + 193;
        pairs(p + 4289, n - 4289, 80, true, pal.constData(), g);
    } else if(e == QLatin1String("idf")){                                     // iCE Draw: run-length pairs, font and palette last
        if(n < 12 + 4096 + 48) return false;
        const int w = (p[8] | p[9] << 8) + 1;
        if(w < 1 || w > 4096) return false;
        for(int i = 0; i < 16; ++i) pal[i] = sixBit(p + n - 48 + i * 3);
        font = p + n - 48 - 4096;
        QByteArray cells;
        for(qint64 o = 12; o + 1 < n - 4096 - 48 && cells.size() < 8000000; ){
            if(p[o] == 1 && p[o + 1] == 0 && o + 5 < n){ const int rep = p[o + 2]; for(int r = 0; r < rep; ++r){ cells.append(char(p[o + 4])); cells.append(char(p[o + 5])); } o += 6; }
            else { cells.append(char(p[o])); cells.append(char(p[o + 1])); o += 2; }
        }
        pairs(reinterpret_cast<const uchar*>(cells.constData()), cells.size(), w, true, pal.constData(), g);
    } else if(e == QLatin1String("pcb")){                                     // PCBoard: @X<bg><fg> colour codes
        g.columns = sauceWidth > 0 ? sauceWidth : 80;
        int row = 0, col = 0, fg = 7, bg = 0;
        auto hex = [](uchar c){ return c >= '0' && c <= '9' ? c - '0' : (c | 32) >= 'a' && (c | 32) <= 'f' ? (c | 32) - 'a' + 10 : -1; };
        for(qint64 o = 0; o < n; ++o){
            if(col >= g.columns){ ++row; col = 0; }
            const uchar c = p[o];
            if(c == 0x1a) break;
            if(c == '\n'){ ++row; col = 0; continue; }
            if(c == '\r') continue;
            if(c == '\t'){ col += 8 - col % 8; continue; }
            if(c == '@' && o + 3 < n && p[o + 1] == 'X' && hex(p[o + 2]) >= 0 && hex(p[o + 3]) >= 0){ bg = hex(p[o + 2]); fg = hex(p[o + 3]); o += 3; continue; }
            if(c == '@' && o + 4 < n && !std::memcmp(p + o + 1, "CLS@", 4)){ row = col = 0; g.cells.clear(); g.rows = 0; o += 4; continue; }
            if(c == '@' && o + 5 < n && !std::memcmp(p + o + 1, "POS:", 4)){ qint64 q = o + 5; int v = 0; while(q < n && p[q] >= '0' && p[q] <= '9'){ v = v * 10 + p[q] - '0'; ++q; } if(q < n && p[q] == '@'){ col = qMax(0, v - 1); o = q; continue; } }
            Cell cell; cell.ch = c; cell.fg = pal[fg]; cell.bg = pal[ice ? bg : (bg & 7)]; g.put(row, col++, cell);
        }
    } else if(e == QLatin1String("bin") || dataType == 5){                     // raw screen memory
        const qint64 cellCount = n / 2;                                       // no width given: 160 columns if whole rows fit, else 80
        const int w = dataType == 5 && fileType > 0 ? fileType * 2 : sauceWidth > 0 ? sauceWidth : (cellCount % 160 && !(cellCount % 80)) ? 80 : 160;
        pairs(p, n, w, ice, pal.constData(), g);
    } else {                                                                  // ANSI / CP437 text
        g.columns = (sauceWidth > 0 && sauceWidth <= 4096) ? sauceWidth : 80;
        ansi(p, n, ice, g);
    }
    if(g.cells.isEmpty()) return false;
    const int rows = g.rows;
    Q_UNUSED(sauceRows);
    const int cw = nine && fontH == 16 ? 9 : 8;
    if(qint64(g.columns) * cw * rows * fontH > (qint64(1) << 28)) return false;
    QImage img(g.columns * cw, rows * fontH, QImage::Format_ARGB32);
    if(img.isNull()) return false;
    img.fill(kAnsi[0]);
    for(auto it = g.cells.constBegin(); it != g.cells.constEnd(); ++it){
        const int row = int(it.key() >> 16), col = int(it.key() & 0xffff); const Cell& c = it.value();
        const uchar* glyph = (c.high && highFont ? highFont : font) + qint64(c.ch) * fontH;
        for(int y = 0; y < fontH; ++y){
            QRgb* d = reinterpret_cast<QRgb*>(img.scanLine(row * fontH + y)) + col * cw;
            const int bits = glyph[y];
            for(int x = 0; x < 8; ++x) d[x] = (bits >> (7 - x)) & 1 ? c.fg : c.bg;
            if(cw == 9) d[8] = (c.ch >= 0xc0 && c.ch <= 0xdf && (bits & 1)) ? c.fg : c.bg;   // line-drawing characters reach across the gap
        }
    }
    out->image = img; out->columns = g.columns; out->rows = rows;
    return true;
}

