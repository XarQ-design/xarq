// CGA colours in ANSI order (black, red, green, brown, blue, magenta, cyan, grey, then bright) and the
// IBM attribute order (blue bit first) that binary formats use.
const QRgb kAnsi[16] = { 0xff000000, 0xffaa0000, 0xff00aa00, 0xffaa5500, 0xff0000aa, 0xffaa00aa, 0xff00aaaa, 0xffaaaaaa,
                         0xff555555, 0xffff5555, 0xff55ff55, 0xffffff55, 0xff5555ff, 0xffff55ff, 0xff55ffff, 0xffffffff };
const int kIbmToAnsi[16] = { 0, 4, 2, 6, 1, 5, 3, 7, 8, 12, 10, 14, 9, 13, 11, 15 };

struct Cell { uchar ch = ' '; QRgb fg = 0xffaaaaaa, bg = 0xff000000; bool high = false; };
struct Grid {
    int columns = 80; QHash<qint64, Cell> cells; int rows = 0;
    void put(int row, int col, const Cell& c){ if(row < 0 || col < 0 || col >= columns || row > 100000 || cells.size() > 4000000) return; cells.insert(qint64(row) << 16 | col, c); rows = qMax(rows, row + 1); }
};

QRgb sixBit(const uchar* p){ auto e = [](int v){ v &= 63; return v << 2 | v >> 4; }; return qRgb(e(p[0]), e(p[1]), e(p[2])); }

void ansi(const uchar* p, qint64 n, bool ice, Grid& g){
    int row = 0, col = 0, savedRow = 0, savedCol = 0, fg = 7, bg = 0; bool bold = false, blink = false, invert = false;
    QRgb fg24 = 0, bg24 = 0;
    for(qint64 i = 0; i < n; ++i){
        if(col >= g.columns){ ++row; col = 0; }
        const uchar c = p[i];
        if(c == '\n'){ ++row; col = 0; continue; }
        if(c == '\r') continue;
        if(c == '\t'){ col += 8 - col % 8; continue; }
        if(c == 0x1a) break;
        if(c == 0x1b && i + 1 < n && p[i + 1] == '['){
            qint64 j = i + 2; QByteArray args;
            while(j < n && j - i < 64 && !((p[j] >= 'A' && p[j] <= 'Z') || (p[j] >= 'a' && p[j] <= 'z'))) args.append(char(p[j++]));
            if(j >= n) break;
            const char cmd = char(p[j]); i = j;
            const QList<QByteArray> parts = args.split(';');
            auto num = [&](int k, int def){ if(k >= parts.size()) return def; bool ok = false; const int v = parts[k].toInt(&ok); return ok ? v : def; };
            switch(cmd){
            case 'H': case 'f': row = qMax(1, num(0, 1)) - 1; col = qMax(1, num(1, 1)) - 1; break;
            case 'A': row = qMax(0, row - qMax(1, num(0, 1))); break;
            case 'B': row += qMax(1, num(0, 1)); break;
            case 'C': col = qMin(g.columns, col + qMax(1, num(0, 1))); break;
            case 'D': col = qMax(0, col - qMax(1, num(0, 1))); break;
            case 's': savedRow = row; savedCol = col; break;
            case 'u': row = savedRow; col = savedCol; break;
            case 'J': if(num(0, 0) == 2){ row = col = 0; g.cells.clear(); g.rows = 0; } break;
            case 't': {                                                    // PabloDraw 24-bit colour
                const QRgb rgb = qRgb(num(1, 0) & 255, num(2, 0) & 255, num(3, 0) & 255);
                if(num(0, -1) == 0) bg24 = rgb; else if(num(0, -1) == 1) fg24 = rgb;
            } break;
            case 'm':
                for(int k = 0; k < qMax(1, int(parts.size())); ++k){
                    const int v = num(k, 0);
                    if(v == 0){ fg = 7; bg = 0; bold = blink = invert = false; fg24 = bg24 = 0; }
                    else if(v == 1){ bold = true; fg24 = 0; }
                    else if(v == 5){ blink = true; bg24 = 0; }
                    else if(v == 7) invert = true;
                    else if(v == 22) bold = false;
                    else if(v == 25) blink = false;
                    else if(v == 27) invert = false;
                    else if(v >= 30 && v <= 37){ fg = v - 30; fg24 = 0; }
                    else if(v >= 40 && v <= 47){ bg = v - 40; bg24 = 0; }
                    else if((v == 38 || v == 48) && num(k + 1, 0) == 2){ const QRgb rgb = qRgb(num(k + 2, 0) & 255, num(k + 3, 0) & 255, num(k + 4, 0) & 255); (v == 38 ? fg24 : bg24) = rgb; k += 4; }
                    else if((v == 38 || v == 48) && num(k + 1, 0) == 5){
                        const int x = num(k + 2, 0) & 255; QRgb rgb;
                        if(x < 16) rgb = kAnsi[x];
                        else if(x < 232){ const int y = x - 16; auto lv = [](int q){ return q ? 55 + q * 40 : 0; }; rgb = qRgb(lv(y / 36), lv((y / 6) % 6), lv(y % 6)); }
                        else { const int gr = 8 + (x - 232) * 10; rgb = qRgb(gr, gr, gr); }
                        (v == 38 ? fg24 : bg24) = rgb; k += 2;
                    }
                }
                break;
            default: break;
            }
            continue;
        }
        Cell cell; cell.ch = c;
        QRgb f = fg24 ? fg24 : kAnsi[fg + (bold ? 8 : 0)], b = bg24 ? bg24 : kAnsi[bg + (blink && ice ? 8 : 0)];
        if(invert) std::swap(f, b);
        cell.fg = f; cell.bg = b;
        g.put(row, col, cell); ++col;
    }
}

// Character + attribute pairs, `width` per row, in the IBM attribute order.
void pairs(const uchar* p, qint64 n, int width, bool ice, const QRgb* pal, Grid& g, int startRow = 0){
    g.columns = width;
    for(qint64 i = 0; i + 1 < n; i += 2){
        const qint64 k = i / 2; Cell c; c.ch = p[i]; const int a = p[i + 1];
        int bg = a >> 4; if(!ice) bg &= 7;
        c.fg = pal[a & 15]; c.bg = pal[bg];
        g.put(startRow + int(k / width), int(k % width), c);
    }
}

